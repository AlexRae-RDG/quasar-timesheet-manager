def draw_logo_mark(canvas, size=28, pad=1):
    """Draw a small vector 'app icon' badge -- deliberately not an emoji or
    symbol-font glyph, since those aren't reliably available on every
    machine (headless/minimal Linux installs in particular)."""
    canvas.delete("all")
    rounded_rect(canvas, pad, pad, pad + size, pad + size, radius=7, fill=ACCENT, outline="")
    rounded_rect(canvas, pad + 5, pad + 5, pad + size - 5, pad + 10, radius=2, fill="white", outline="")
    canvas.create_oval(pad + 5, pad + 14, pad + 12, pad + 21, fill="white", outline="")
    canvas.create_oval(pad + size - 12, pad + 14, pad + size - 5, pad + 21, fill="white", outline="")


def draw_theme_swatch(canvas, theme_id: str, selected: bool, width=132, height=88):
    """Draw a small live preview card for one theme onto `canvas`, using
    that theme's own palette directly (not the app's currently-active
    globals above) -- this is what lets Settings show every preset side by
    side regardless of which one is actually active right now. Works for
    "custom" exactly like any other id -- get_theme() builds its palette
    live from the user's current seed colors either way.

    Mimics the real app's look in miniature: an app-background canvas, a
    panel "card" inset into it, and a couple of colored bars standing in
    for time blocks -- plus a filled corner badge when this is the
    currently-selected theme, the same "selected" convention used for
    project-color swatches elsewhere (see panels.ProjectPanel)."""
    canvas.delete("all")
    p = get_theme(theme_id)["palette"]

    rounded_rect(canvas, 1, 1, width - 1, height - 1, radius=10, fill=p["APP_BG"], outline="")

    card_pad = 10
    card_top = 10
    rounded_rect(canvas, card_pad, card_top, width - card_pad, height - 12,
                 radius=6, fill=p["PANEL_BG"], outline=p["BORDER"], width=1)

    # A couple of small "time block" bars in the accent + a muted neutral,
    # just enough to suggest the calendar without drawing the whole thing.
    bar_x = card_pad + 8
    bar_w = width - 2 * (card_pad + 8)
    rounded_rect(canvas, bar_x, card_top + 12, bar_x + bar_w, card_top + 26,
                 radius=3, fill=p["ACCENT"], outline="")
    rounded_rect(canvas, bar_x, card_top + 32, bar_x + bar_w * 0.62, card_top + 46,
                 radius=3, fill=p["BORDER_STRONG"], outline="")

    outline_color = p["ACCENT"] if selected else p["BORDER_STRONG"]
    outline_width = 3 if selected else 1
    rounded_rect(canvas, 1, 1, width - 1, height - 1, radius=10, outline=outline_color,
                 width=outline_width, fill="")

    if selected:
        badge_r = 9
        bx, by = width - 14, 14
        canvas.create_oval(bx - badge_r, by - badge_r, bx + badge_r, by + badge_r,
                            fill=p["ACCENT"], outline="")
        canvas.create_line(bx - 4, by, bx - 1, by + 3, bx + 4, by - 4,
                            fill="white", width=2, capstyle="round", joinstyle="round")


def rounded_rect(canvas, x1, y1, x2, y2, radius: float = 8, exponent: float = 4.0, **kwargs):
    """Draw a rounded rectangle on `canvas`, as a single polygon item.

    This has gone through two worse designs before landing here, both
    visible as real "artifacts" reported on real hardware (a Retina
    MacBook) that a plain-DPI Linux test environment never surfaced:

    1. Originally a single `create_polygon(..., smooth=True)` -- Tk's
       polygon smoothing approximates a spline *near* its control points
       rather than through them, which could leave a sliver of the
       canvas's flat background color poking out right at a corner.
    2. Then rewritten as several composited items per shape (quarter-circle
       "pieslice" arcs for the fill, plain arc outlines for the border,
       plus rectangles/lines for the straight edges) to get true circular
       corners. That fixed (1) but traded it for a worse, platform-specific
       problem: Tk's `create_arc` outline rendering (particularly with a
       thicker `width`, as the Settings theme-picker's selected-swatch ring
       uses) can draw past the arc's own bounding box at the start/end caps
       on some Tk builds -- visible as a small square notch poking out at
       a corner, exactly where the previous approach left a gap instead.

    This version samples real trigonometric points around each corner's
    true circular arc (no spline approximation) and draws the WHOLE shape
    -- all four corners and the straight edges between them -- as one
    `create_polygon` call, which natively supports fill AND outline
    together. One item means no seam between separately-drawn pieces is
    possible, and no per-item arc/line stroke-cap quirks either.

    `exponent` controls the corner *curve family*, not just its radius.
    2.0 is a true circular arc (the original design). Apple's "continuous
    corner" / squircle rounding used throughout iOS and macOS is smoother
    than a circular arc -- it keeps curving into the straight edge instead
    of meeting it at an abrupt tangent point -- and is commonly approximated
    with a superellipse of degree ~4-5. This defaults to 4.0 so every
    rounded shape in the app (buttons, cards, the calendar's own corners)
    reads as "Apple-style" without every call site needing to opt in.

    Returns the created item id (useful for the one caller --
    calendar_view._draw_entry -- that stacks its label text via
    `tag_raise(text_item, this_return_value)`).
    """
    x1, x2 = (x1, x2) if x1 <= x2 else (x2, x1)
    y1, y2 = (y1, y2) if y1 <= y2 else (y2, y1)
    radius = max(0.0, min(radius, (x2 - x1) / 2, (y2 - y1) / 2))

    if radius <= 0:
        return canvas.create_rectangle(x1, y1, x2, y2, **kwargs)

    # Each corner's own center plus the start/end angle (degrees, standard
    # math convention: 0=east, 90=north) of the quarter-circle arc that
    # belongs to it. Consecutive corners are listed so each one's end angle
    # picks up where the next begins (90 -> 0 -> -90 -> -180 -> back to 90),
    # one continuous sweep around the whole shape -- the straight edges
    # need no separate points at all, since a polygon already connects
    # consecutive points with straight lines, and each arc's sampled
    # endpoints already sit exactly on the straight edges (e.g. the
    # top-right corner's start point, at angle 90, is (x2-radius, y1) --
    # precisely where the top edge ends).
    corners = [
        (x2 - radius, y1 + radius, 90, 0),      # top-right
        (x2 - radius, y2 - radius, 0, -90),     # bottom-right
        (x1 + radius, y2 - radius, -90, -180),  # bottom-left
        (x1 + radius, y1 + radius, -180, -270),  # top-left
    ]
    steps = 10  # points per 90-degree corner -- plenty smooth at any size used in this app
    # Superellipse exponent: |cos|**(2/n) in place of plain cos generalizes
    # the circle (n=2, where 2/n=1 and this collapses back to plain cos)
    # into Apple's flatter-curved, longer-tangent "continuous corner" shape
    # for n>2. copysign keeps each term's original sign since abs() strips
    # it before the fractional power (a negative base to a fractional power
    # is undefined/complex in general).
    power = 2.0 / exponent
    points = []
    for cx, cy, start_deg, end_deg in corners:
        for i in range(steps + 1):
            deg = start_deg + (end_deg - start_deg) * i / steps
            rad = math.radians(deg)
            cos_v = math.cos(rad)
            sin_v = math.sin(rad)
            points.append(cx + radius * math.copysign(abs(cos_v) ** power, cos_v))
            # Canvas y increases downward (screen coordinates), unlike the
            # standard math y-axis this angle convention assumes -- so the
            # sign flips here to keep "up" (positive sin) meaning a
            # smaller y on screen.
            points.append(cy - radius * math.copysign(abs(sin_v) ** power, sin_v))
    return canvas.create_polygon(points, **kwargs)
