"""
Modern visual theme: eighteen curated color palettes, a dynamic "Match
System Appearance" theme, and a fully custom one, font resolution, ttk
styling, and canvas drawing helpers (rounded rects, logo mark,
theme-swatch previews) shared across the app.

Colors are exposed as plain module attributes (theme.PANEL_BG, etc.) so
existing code can keep reading `theme.SOMETHING` without changes. What
switches at runtime is *which* palette those names point at -- call
set_theme("theme_id") to flip them, then re-run apply_theme(root) and
rebuild any plain (non-ttk) widgets so they pick up the new colors (ttk
widgets update automatically via the style engine; raw tk widgets like
Frame/Label/Canvas cache their bg/fg at construction time and need to be
rebuilt -- see MainWindow._apply_theme_and_rebuild).

This used to be a hand-tuned set of seven palettes, each with all ~24
colors picked independently. It's now eighteen palettes -- inspired by
the mood categories (Monochromatic, Romantic, Playful, Vibrant, Neutral,
Tranquil, Seasonal) on Figma's "100 color combinations" resource
(figma.com/resource-library/color-combinations) -- plus "Match System
Appearance", which follows the OS's light/dark setting instead of being
hand-picked, and a "Custom" entry the user builds themselves from a
color picker (see panels.SettingsPanel's custom-color row). Rather than hand-picking all
~24 colors per palette again (error-prone at this count, and the whole
point of a user-driven custom option), every palette -- curated or
custom alike -- is generated by derive_palette() below from just a
handful of seed colors: a background, a panel color, a primary text
color, and an accent. Everything else (borders, muted text, hover/soft
accent tints, grid lines, etc.) is computed from those four using the
same proportional relationships the original seven hand-tuned palettes
actually had (verified by measuring them before writing this).
"""
