# ---------------------------------------------------------------------------
# Color math -- small helpers used only to derive a full ~24-color palette
# from a handful of seed colors (see derive_palette below).
# ---------------------------------------------------------------------------
def _hex_to_rgb(hex_color: str):
    h = hex_color.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _rgb_to_hex(rgb) -> str:
    return "#{:02X}{:02X}{:02X}".format(*(max(0, min(255, round(c))) for c in rgb))


def _mix(color_a: str, color_b: str, t: float) -> str:
    """Blend from color_a toward color_b by fraction t (0 = color_a,
    1 = color_b), in plain sRGB. Not perceptually uniform, but plenty
    good enough at the small t values every derived color below uses,
    and it's what the hand-tuned originals turn out to approximate too."""
    a, b = _hex_to_rgb(color_a), _hex_to_rgb(color_b)
    return _rgb_to_hex(a[i] + (b[i] - a[i]) * t for i in range(3))


def _darken(color: str, amount: float) -> str:
    """Multiply each channel toward black by `amount` (0 = unchanged,
    1 = black) -- used for ACCENT_HOVER, a plain darken rather than a mix
    toward some other color."""
    r, g, b = _hex_to_rgb(color)
    factor = 1.0 - amount
    return _rgb_to_hex((r * factor, g * factor, b * factor))


def _is_dark(color: str) -> bool:
    """Perceptual-ish luminance check used only to decide which side of a
    couple of mode-dependent rules (FIELD_BG, SURFACE, default danger/now
    -line colors) a seed palette falls on -- there's no separate light/
    dark toggle the user sets; it's inferred from the panel color itself."""
    r, g, b = _hex_to_rgb(color)
    luminance = 0.299 * r + 0.587 * g + 0.114 * b
    return luminance < 128


def derive_palette(app_bg: str, panel_bg: str, text_primary: str, accent: str,
                    danger: str = None, now_line: str = None) -> dict:
    """Build a full ~24-color palette from four required seed colors (an
    app background, a panel/card background, a primary text color, and an
    accent) plus two optional ones (a danger/delete red and a "now" line
    color -- sensible mode-appropriate defaults are used if omitted).

    This is the one place that turns "a few colors someone picked" into
    "a fully-themed app" -- used for every one of the twenty curated
    palettes below (each just supplies its own seeds) and for the user's
    own Custom palette (panels.SettingsPanel's four color pickers feed
    straight into this)."""
    dark = _is_dark(panel_bg)
    if danger is None:
        danger = "#E5484D" if dark else "#D6334C"
    if now_line is None:
        now_line = "#FF9500" if dark else "#FF5A36"

    field_bg = _mix(panel_bg, text_primary, 0.035) if dark else panel_bg
    accent_hover = _darken(accent, 0.17)
    accent_soft = _mix(panel_bg, accent, 0.11)

    return {
        "APP_BG": app_bg,
        "PANEL_BG": panel_bg,
        "BORDER": _mix(panel_bg, text_primary, 0.065),
        "BORDER_STRONG": _mix(panel_bg, text_primary, 0.12),
        "TEXT_PRIMARY": text_primary,
        "TEXT_SECONDARY": _mix(text_primary, panel_bg, 0.38),
        "TEXT_MUTED": _mix(text_primary, panel_bg, 0.63),
        "ACCENT": accent,
        "ACCENT_HOVER": accent_hover,
        "ACCENT_SOFT": accent_soft,
        "DANGER": danger,
        "DANGER_SOFT": _mix(panel_bg, danger, 0.08),
        "DANGER_SOFT_ACTIVE": _mix(panel_bg, danger, 0.16),
        "GRID_LINE": _mix(panel_bg, text_primary, 0.04),
        "GRID_LINE_HOUR": _mix(panel_bg, text_primary, 0.10),
        "HEADER_BG": _mix(panel_bg, text_primary, 0.045),
        "TODAY_TINT": accent_soft,
        "NOW_LINE": now_line,
        "BLOCK_BORDER": panel_bg,
        "SELECTION_OUTLINE": text_primary,
        "PREVIEW_FILL": accent,
        "PREVIEW_OUTLINE": accent_hover,
        "FIELD_BG": field_bg,
        "SURFACE": field_bg if dark else app_bg,
    }


